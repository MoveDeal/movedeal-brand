window.MD_BRAND_applyLang = function applyLang(lang) {
  const dict = window.MD_BRAND_I18N[lang] || window.MD_BRAND_I18N.en
  document.documentElement.lang = lang === "de" ? "de" : "en"
  document.title = dict.docTitle
  const meta = document.querySelector('meta[name="description"]')
  if (meta) meta.setAttribute("content", dict.metaDesc)
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n")
    if (key && dict[key] != null) el.textContent = dict[key]
  })
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    const active = btn.getAttribute("data-lang-btn") === lang
    btn.setAttribute("aria-pressed", active ? "true" : "false")
    btn.classList.toggle("is-active", active)
  })
  try {
    localStorage.setItem("md-brand-lang", lang)
  } catch (_) {}
  const url = new URL(window.location.href)
  url.searchParams.set("lang", lang)
  history.replaceState(null, "", url.pathname + url.search + url.hash)
}

document.addEventListener("DOMContentLoaded", () => {
  const params = new URLSearchParams(window.location.search)
  const fromUrl = params.get("lang")
  const fromStore = (() => {
    try {
      return localStorage.getItem("md-brand-lang")
    } catch (_) {
      return null
    }
  })()
  const browser = (navigator.language || "en").toLowerCase().startsWith("de") ? "de" : "en"
  const lang = fromUrl === "de" || fromUrl === "en" ? fromUrl : fromStore === "de" || fromStore === "en" ? fromStore : browser
  window.MD_BRAND_applyLang(lang)
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.addEventListener("click", () => window.MD_BRAND_applyLang(btn.getAttribute("data-lang-btn")))
  })
})
